function love.conf(t)
    t.identity = "JawbladeTetris"
    t.version = "11.5"
    t.console = false
    t.window.title = "Jawblade Tetris"
    t.window.width = 640
    t.window.height = 480
    t.window.resizable = false
    t.window.fullscreen = true
    t.window.fullscreentype = "desktop"
    t.window.vsync = 1
    t.window.msaa = 0
end
